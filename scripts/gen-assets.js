// Generates the app icon, tray icons and badge overlay as PNG files.
// Run: node scripts/gen-assets.js
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

const glyph = (roof, bubble, dots) => `
  <path d="M282 486 L512 316 L742 486" fill="none" stroke="${roof}" stroke-width="64" stroke-linecap="round" stroke-linejoin="round"/>
  <path d="M400 548 H624 A72 72 0 0 1 696 620 V686 A72 72 0 0 1 624 758 H468 L392 818 L404 754 A72 72 0 0 1 328 686 V620 A72 72 0 0 1 400 548 Z" fill="${bubble}"/>
  ${dots ? `<circle cx="436" cy="653" r="27" fill="${dots}"/><circle cx="512" cy="653" r="27" fill="${dots}"/><circle cx="588" cy="653" r="27" fill="${dots}"/>` : ''}
`;

const appIcon = `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#4459CF"/>
      <stop offset="1" stop-color="#28368C"/>
    </linearGradient>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="186" fill="url(#bg)"/>
  <g transform="translate(0 -46)">${glyph('#FFFFFF', '#F2B33D', '#2E3D99')}</g>
</svg>`;

// Full-bleed variant for Windows/Linux small sizes (less padding reads better at 16–32px)
const appIconFull = `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#4459CF"/>
      <stop offset="1" stop-color="#28368C"/>
    </linearGradient>
  </defs>
  <rect x="24" y="24" width="976" height="976" rx="220" fill="url(#bg)"/>
  <g transform="translate(-61 -113) scale(1.12)">${glyph('#FFFFFF', '#F2B33D', '#2E3D99')}</g>
</svg>`;

// macOS menu-bar template image: black glyph on transparent
const trayTemplate = `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="200 250 624 624">
  ${glyph('#000000', '#000000', null)}
</svg>`;

const badge = `
<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
  <circle cx="32" cy="32" r="28" fill="#E5484D" stroke="#FFFFFF" stroke-width="6"/>
</svg>`;

async function png(svg, size, file) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(path.join(root, file));
}

(async () => {
  fs.mkdirSync(path.join(root, 'build'), { recursive: true });
  fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
  await png(appIcon, 1024, 'build/icon.png');            // macOS (icns generated by electron-builder)
  await png(appIconFull, 256, 'build/icon-win.png');      // Windows (ico generated by electron-builder)
  await png(appIconFull, 512, 'assets/icon.png');         // window icon (Linux/Windows)
  await png(appIconFull, 32, 'assets/tray.png');          // Windows tray
  await png(appIconFull, 16, 'assets/tray-16.png');
  await png(trayTemplate, 18, 'assets/trayTemplate.png'); // macOS tray
  await png(trayTemplate, 36, 'assets/trayTemplate@2x.png');
  await png(badge, 16, 'assets/badge.png');
  await png(badge, 32, 'assets/badge@2x.png');
  console.log('assets generated');
})();
