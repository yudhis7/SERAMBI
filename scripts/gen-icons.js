const fs = require('fs');
const path = require('path');

const names = [
  'house', 'square-pen', 'calendar-days', 'settings', 'plus', 'arrow-left', 'arrow-right',
  'rotate-cw', 'ellipsis', 'image', 'clock', 'check', 'send', 'copy', 'trash-2', 'x', 'bell',
  'bell-off', 'panel-left-close', 'panel-left-open', 'external-link', 'log-out', 'pencil', 'sun',
  'moon', 'monitor', 'chevron-left', 'chevron-right', 'file-text', 'circle-alert', 'list',
  'calendar', 'copy-plus', 'download', 'upload', 'bot', 'search', 'info', 'clipboard-copy',
  'grip-vertical', 'zoom-in', 'zoom-out', 'circle-check-big', 'hourglass', 'bookmark-plus',
  'message-circle', 'bookmark', 'bookmark-check', 'store', 'link', 'shopping-bag', 'circle-arrow-down',
  'mail', 'house-plus', 'refresh-cw', 'badge-info', 'copyright'
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1]
    .replace(/\s*\n\s*/g, '');
  out[n] = inner;
}

const js = `// Serambi — Copyright (c) 2026 Yudhistira <yudhie7@gmail.com>. All rights reserved.\n// Icons from Lucide (https://lucide.dev), ISC License. Generated by scripts/gen-icons.js
const PATHS = ${JSON.stringify(out, null, 0)};
export function icon(name, size = 18, extra = '') {
  const p = PATHS[name] || '';
  return \`<svg class="ic \${extra}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${p}</svg>\`;
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'icons.js'), js);
console.log('icons:', Object.keys(out).length);
